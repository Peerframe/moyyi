import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const desktop = join(root, "apps/desktop");
const ids: unknown = JSON.parse(readFileSync(join(desktop, "feature-list.json"), "utf8"));
if (
  !Array.isArray(ids) ||
  ids.some((id) => typeof id !== "string" || !/^[a-z][a-z0-9-]*$/.test(id)) ||
  new Set(ids).size !== ids.length
)
  throw Error("Invalid desktop feature list");
const checking = process.argv.includes("--check");
function emit(file: string, input: string): void {
  const path = join(desktop, file);
  const source = execFileSync(
    join(root, "node_modules/.bin/biome"),
    ["check", "--write", "--unsafe", `--stdin-file-path=${path}`],
    { input, encoding: "utf8" },
  );
  if (checking) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== source)
      throw Error(`Stale ${file}; run node scripts/desktop-feature-registry.ts`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, source);
  }
}
emit(
  "shared-feature-types.ts",
  [
    "// Generated by scripts/desktop-feature-registry.ts from feature-list.json. Do not edit.",
    ...ids.map(
      (id, index) =>
        `import type { FeatureState as State${index}, FeatureCommand as Command${index}, FeatureAction as Action${index}, FeatureBridge as Bridge${index} } from "./features/${id}/contract.ts";`,
    ),
    `export type FeatureStates = ${ids.map((_, index) => `State${index}`).join(" & ")};`,
    `export type FeatureCommands = ${ids.map((_, index) => `Command${index}`).join(" | ")};`,
    `export type FeatureActions = ${ids.map((_, index) => `Action${index}`).join(" | ")};`,
    `export type FeatureBridges = ${ids.map((_, index) => `Bridge${index}`).join(" & ")};`,
    "",
  ].join("\n"),
);
const commands = ids.filter((id) => existsSync(join(desktop, "features", id, "validation.ts")));
emit(
  "host/command-registry.ts",
  [
    "// Generated by scripts/desktop-feature-registry.ts from feature-list.json. Do not edit.",
    'import type { CommandValidator } from "./validation-primitives.ts";',
    ...commands.flatMap((id, index) => [
      `import { commandTypes as types${index} } from "../features/${id}/contract.ts";`,
      `import { validateCommand as validate${index} } from "../features/${id}/validation.ts";`,
    ]),
    "export const commandValidators = new Map<string, CommandValidator>();",
    ...commands.map(
      (_, index) =>
        `for (const type of types${index}) { if (commandValidators.has(type)) throw Error(\`Duplicate desktop command: \${type}\`); commandValidators.set(type, validate${index}); }`,
    ),
    "",
  ].join("\n"),
);
for (const target of [
  {
    file: "native/contracts.ts",
    entry: "contract.ts",
    symbol: "contract",
    name: "featureContracts",
    type: "FeatureContract",
    from: "./contract.ts",
    required: true,
  },
  {
    file: "native/feature-registry.ts",
    entry: "main.ts",
    symbol: "nativeFeature",
    name: "nativeFeatures",
  },
  {
    file: "host/feature-registry.ts",
    entry: "host.ts",
    symbol: "hostFeature",
    name: "hostFeatures",
  },
  {
    file: "renderer/feature-registry.ts",
    entry: "renderer/index.tsx",
    symbol: "rendererFeature",
    name: "rendererFeatures",
  },
]) {
  const entries = ids.filter((id) => {
    const exists = existsSync(join(desktop, "features", id, target.entry));
    if (target.required && !exists) throw Error(`Missing desktop feature ${id}/${target.entry}`);
    return exists;
  });
  const imports = entries.map(
    (id, index) =>
      `import { ${target.symbol} as feature${index} } from "../features/${id}/${target.entry}";`,
  );
  const source = [
    "// Generated by scripts/desktop-feature-registry.ts from feature-list.json. Do not edit.",
    ...(target.type ? [`import type { ${target.type} } from "${target.from}";`] : []),
    ...imports,
    `export const ${target.name}${target.type ? `: readonly ${target.type}[]` : ""} = [${entries.map((_, index) => `feature${index}`).join(", ")}];`,
    "",
  ].join("\n");
  emit(target.file, source);
}
